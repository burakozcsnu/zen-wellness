-- Baseline for a FRESH database: the six core tables that were originally created by hand in the
-- Supabase dashboard and are therefore not created by migrate*.js. Captured from production's schema
-- (structure only, no data). Safe to re-run (IF NOT EXISTS). Used by scripts/seed-test-db.js only.

CREATE TABLE IF NOT EXISTS uyeler (
  id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  ad_soyad text NOT NULL,
  cinsiyet text,
  brans text,
  kayit_tarihi date DEFAULT CURRENT_DATE,
  boy numeric,
  auth_user_id uuid,
  email text,
  telefon text,
  dogum_tarihi date,
  saglik_gecmisi text,
  alerjiler text,
  beslenme_aliskanliklari text,
  hareket_aliskanliklari text,
  spor_gecmisi text,
  beklentiler text,
  degerlendirme_verileri jsonb DEFAULT '{}'::jsonb,
  degerlendirme_tamamlandi boolean DEFAULT false NOT NULL,
  degerlendirme_tarihi timestamp with time zone,
  trainer_id text,
  CONSTRAINT uyeler_auth_user_id_key UNIQUE (auth_user_id),
  CONSTRAINT uyeler_pkey PRIMARY KEY (id)
);

CREATE TABLE IF NOT EXISTS programlar (
  id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  program_adi text NOT NULL,
  detaylar jsonb,
  CONSTRAINT programlar_pkey PRIMARY KEY (id)
);

CREATE TABLE IF NOT EXISTS olcumler (
  id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  member_id bigint,
  tarih date DEFAULT CURRENT_DATE,
  weight numeric,
  fat numeric,
  waist numeric,
  chest numeric,
  neck numeric,
  l_arm numeric,
  r_arm numeric,
  l_leg numeric,
  r_leg numeric,
  hips numeric,
  sol_onkol numeric,
  sag_onkol numeric,
  basen numeric,
  l_bacak numeric,
  r_bacak numeric,
  l_kalf numeric,
  r_kalf numeric,
  CONSTRAINT olcumler_pkey PRIMARY KEY (id)
);

CREATE TABLE IF NOT EXISTS antrenmanlar (
  id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  member_id bigint,
  tarih date DEFAULT CURRENT_DATE,
  sablon text,
  setler jsonb,
  status text DEFAULT 'completed'::text NOT NULL,
  rpe numeric,
  tempo text,
  rest_seconds integer DEFAULT 0 NOT NULL,
  template_id bigint,
  CONSTRAINT antrenmanlar_pkey PRIMARY KEY (id)
);

CREATE TABLE IF NOT EXISTS dokumanlar (
  id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  member_id bigint,
  adi text DEFAULT 'İsimsiz Döküman'::text NOT NULL,
  yol text NOT NULL,
  tip text,
  tarih timestamp with time zone DEFAULT now(),
  CONSTRAINT dokumanlar_pkey PRIMARY KEY (id)
);

CREATE TABLE IF NOT EXISTS master_egzersizler (
  id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  ad text NOT NULL,
  brans text,
  gruplar jsonb DEFAULT '{}'::jsonb,
  body_part text,
  classifications text[] DEFAULT '{}'::text[] NOT NULL,
  style text,
  drill text,
  difficulty text,
  source_url text,
  CONSTRAINT master_egzersizler_ad_key UNIQUE (ad),
  CONSTRAINT master_egzersizler_pkey PRIMARY KEY (id)
);

-- uyeler.trainer_id FK is added by migrate.js once the trainers table exists.
DO $$ BEGIN
  ALTER TABLE olcumler ADD CONSTRAINT olcumler_member_id_fkey FOREIGN KEY (member_id) REFERENCES uyeler(id) ON DELETE CASCADE;
EXCEPTION WHEN duplicate_object THEN NULL; END $$;
DO $$ BEGIN
  ALTER TABLE antrenmanlar ADD CONSTRAINT antrenmanlar_member_id_fkey FOREIGN KEY (member_id) REFERENCES uyeler(id) ON DELETE CASCADE;
EXCEPTION WHEN duplicate_object THEN NULL; END $$;
DO $$ BEGIN
  ALTER TABLE dokumanlar ADD CONSTRAINT dokumanlar_member_id_fkey FOREIGN KEY (member_id) REFERENCES uyeler(id) ON DELETE CASCADE;
EXCEPTION WHEN duplicate_object THEN NULL; END $$;

CREATE INDEX IF NOT EXISTS uyeler_auth_user_id_idx ON uyeler USING btree (auth_user_id);

